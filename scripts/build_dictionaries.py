#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# ==============================================================================
# AUTOMATIC BIDIRECTIONAL DICTIONARY GENERATOR (scripts/build_dictionaries.py)
# ==============================================================================
#
# This script parses technical word pairs from `backmatter/words.tex` and
# generates two alphabetically sorted, grouped LaTeX files:
#   1. `backmatter/dict_fa2en_content.tex` (Persian to English)
#   2. `backmatter/dict_en2fa_content.tex` (English to Persian)
#
# ------------------------------------------------------------------------------
# HOW IT WORKS:
# ------------------------------------------------------------------------------
# - Persian Collation: Correctly handles all 32 Persian alphabet letters,
#   including special characters (پ, چ, ژ, گ, آ, هـ).
# - Normalization: Strips zero-width non-joiners (\u200c / نیم‌فاصله), hyphens,
#   and leading/trailing whitespaces when calculating collation sort keys.
# - Alphabet Grouping: Automatically inserts `\dicalphabet{...}` group headers.
# - Build Hook: Executed automatically by `latexmkrc` during `latexmk` builds,
#   or runnable standalone:
#       python scripts/build_dictionaries.py
# ==============================================================================

import os
import re
import sys

# Collation order for Persian
PERSIAN_ALPHABET_ORDER = 'آاأإءئؤبپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی'
PERSIAN_CHAR_MAP = {c: i for i, c in enumerate(PERSIAN_ALPHABET_ORDER)}

def get_fa_sort_key(word):
    # Normalize: strip diacritics, zero-width non-joiners, spaces, hyphens for sorting
    w = word.strip()
    w_clean = re.sub(r'[\u200c\s\-\_]', '', w)
    key = []
    for ch in w_clean:
        if ch in PERSIAN_CHAR_MAP:
            key.append(PERSIAN_CHAR_MAP[ch])
        else:
            key.append(999)
    return key

def get_fa_group_header(word):
    w = word.strip()
    if not w:
        return ''
    first_char = w[0]
    if first_char == 'آ':
        return 'آ'
    elif first_char in ('ا', 'أ', 'إ'):
        return 'الف'
    elif first_char == 'ه':
        return 'هـ'
    elif first_char in PERSIAN_CHAR_MAP:
        return first_char
    else:
        return first_char

def get_en_sort_key(word):
    w_clean = re.sub(r'[^a-zA-Z0-9]', '', word.lower())
    return w_clean

def get_en_group_header(word):
    w = word.strip()
    if not w:
        return ''
    first_char = w[0].upper()
    return first_char

def parse_words_file(filepath):
    entries = []
    if not os.path.exists(filepath):
        print(f"Error: {filepath} not found.", file=sys.stderr)
        return entries

    with open(filepath, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith('%'):
                continue
            # Matches \dictentry{english}{persian} or \dicentry{...}{...} or \dic{...}{...}
            m = re.match(r'\\(?:dictentry|dicentry|dic)\{([^}]+)\}\{([^}]+)\}', line)
            if m:
                en = m.group(1).strip()
                fa = m.group(2).strip()
                entries.append((en, fa))
    return entries

def generate_fa2en(entries, out_path):
    # Sort by Persian
    sorted_entries = sorted(entries, key=lambda x: get_fa_sort_key(x[1]))
    
    lines = []
    current_header = None
    for en, fa in sorted_entries:
        header = get_fa_group_header(fa)
        if header != current_header:
            current_header = header
            lines.append(f"\n\\dicalphabet{{{current_header}}}")
        lines.append(f"\\dic{{{en}}}{{{fa}}}")
    
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write("% Automatically generated by scripts/build_dictionaries.py - DO NOT EDIT MANUALLY\n")
        f.write("\n".join(lines).strip() + "\n")
    print(f"Generated {out_path} with {len(sorted_entries)} entries.")

def generate_en2fa(entries, out_path):
    # Sort by English
    sorted_entries = sorted(entries, key=lambda x: get_en_sort_key(x[0]))
    
    lines = []
    current_header = None
    for en, fa in sorted_entries:
        header = get_en_group_header(en)
        if header != current_header:
            current_header = header
            lines.append(f"\n\\dicalphabet{{{current_header}}}")
        lines.append(f"\\dic{{{en}}}{{{fa}}}")
    
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write("% Automatically generated by scripts/build_dictionaries.py - DO NOT EDIT MANUALLY\n")
        f.write("\n".join(lines).strip() + "\n")
    print(f"Generated {out_path} with {len(sorted_entries)} entries.")

def main():
    # Assume workspace root is the parent directory of this script
    script_dir = os.path.dirname(os.path.abspath(__file__))
    workspace_dir = os.path.abspath(os.path.join(script_dir, '..'))
    
    words_file = os.path.join(workspace_dir, 'backmatter', 'words.tex')
    fa2en_file = os.path.join(workspace_dir, 'backmatter', 'dict_fa2en_content.tex')
    en2fa_file = os.path.join(workspace_dir, 'backmatter', 'dict_en2fa_content.tex')
    
    if not os.path.exists(words_file):
        print(f"Warning: {words_file} not found. Skipping dictionary generation.")
        return
    
    entries = parse_words_file(words_file)
    if not entries:
        print("Warning: No dictionary entries found in words.tex.")
        return
        
    generate_fa2en(entries, fa2en_file)
    generate_en2fa(entries, en2fa_file)

if __name__ == '__main__':
    main()
